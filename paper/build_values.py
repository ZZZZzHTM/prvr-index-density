@lru_cache(maxsize=None)
def result_file(name):
    path = (ROOT / name).resolve()
    path.relative_to((ROOT / "results").resolve())
    with path.open(encoding="utf-8-sig") as handle:
        return json.load(handle)

def field(name, pointer):
    item = result_file(name)
    for part in pointer.removeprefix("/").split("/"):
        key = part.replace("~1", "/").replace("~0", "~")
        item = item[int(key)] if isinstance(item, list) else item[key]
    return item

OPERATORS = {ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul,
             ast.Div: operator.truediv, ast.Pow: operator.pow}
FUNCTIONS = {"abs": abs, "min": min, "max": max, "len": len, "floor": math.floor}

def calculate(node, value):
    if isinstance(node, ast.Name):
        return value(node.id)
    if isinstance(node, ast.Constant) and (node.value is None or type(node.value) in (int, float)):
        return node.value
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return -calculate(node.operand, value)
    if isinstance(node, ast.BinOp) and type(node.op) in OPERATORS:
        return OPERATORS[type(node.op)](calculate(node.left, value), calculate(node.right, value))
    if isinstance(node, (ast.Tuple, ast.Set)):
        items = (calculate(child, value) for child in node.elts)
        return tuple(items) if isinstance(node, ast.Tuple) else set(items)
    if (isinstance(node, ast.Compare) and len(node.ops) == 1 and isinstance(node.ops[0], ast.IsNot)
            and isinstance(node.comparators[0], ast.Constant) and node.comparators[0].value is None):
        return calculate(node.left, value) is not None
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in FUNCTIONS:
        return FUNCTIONS[node.func.id](*(calculate(arg, value) for arg in node.args))
    raise ValueError(f"Invalid formula expression: {ast.dump(node)}")

def main():
    with (ROOT / "paper" / "values.csv").open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    ids = [row["id"] for row in rows]
    if ids != [f"V{i:03}" for i in range(1, 174)]:
        raise ValueError("Expected 173 consecutively numbered display rows")
    lookup = dict(AUXILIARY)
    for row in rows:
        rule = row["field_or_formula"]
        lookup[row["id"]] = (row["source_file"], rule) if rule.startswith("/") else rule

    @lru_cache(maxsize=None)
    def value(name):
        rule = lookup[name]
        if isinstance(rule, tuple):
            return field(*rule)
        return calculate(ast.parse(rule, mode="eval").body, value)

    matched = 0
    for row in rows:
        name = row["id"]
        rendered = format(value(name), SOURCE_FORMATS[name])
        if name in NORMALIZE_NEGATIVE_ZERO and float(rendered) == 0:
            rendered = format(0, SOURCE_FORMATS[name])
        if rendered == row["display"]:
            matched += 1
        else:
            print(f"{name} ({row['paper_location']}): calculated {rendered}, expected {row['display']}")
    print(f"{matched}/{len(rows)} match")
    # The introduction uses a separate typesetting alias for a million-entry fp32 projection.
    projection = format(value("V008") * 10, ".0f")
    print(f"Additional introduction value: {projection} GiB (expected 229)")
    return 0 if matched == len(rows) and projection == "229" else 1

